'use server';

import { createClient } from '@supabase/supabase-js';
import { revalidatePath } from 'next/cache';

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL || '';
const supabaseServiceKey = process.env.SUPABASE_SERVICE_ROLE_KEY || '';
const geminiApiKey = process.env.GEMINI_API_KEY || '';

export async function triggerResearch(topicId: string) {
  const supabase = createClient(supabaseUrl, supabaseServiceKey);

  // 1. Idempotency Check & Atomic Lock
  const { data: topic, error: lockError } = await supabase
    .from('topics')
    .update({ 
      status: 'generating',
      locked_at: new Date().toISOString(),
      last_attempt_at: new Date().toISOString()
    })
    .eq('id', topicId)
    .in('status', ['queued', 'failed', 'delayed']) // Only allow if in these states
    .select()
    .single();

  if (lockError || !topic) {
    return { success: false, error: 'Topic already processing or unavailable' };
  }

  try {
    // 2. Call Research Engine (Simulated for now, would be Gemini API)
    // prompt = "Generate 15 page CA study guide for topic.title"
    const startTime = Date.now();
    
    // FETCH Gemini Deep Research API here
    const mockContent = `# ${topic.title}\n\n## Introduction\nThis is a generated guide for CA Intermediate students...\n\n## Key Concepts\n- Concept 1\n- Concept 2\n\n## Worked Example\n| Item | Amount |\n|---|---|\n| Sales | 10,000 |\n| GST 18% | 1,800 |`;

    const duration = `${Math.floor((Date.now() - startTime) / 1000)} seconds`;

    // 3. Create New Version
    const { data: version, error: versionError } = await supabase
      .from('topic_versions')
      .insert({
        topic_id: topicId,
        version_number: (topic.current_version ?? 0) + 1,
        content: mockContent,
        manual_review_notes: 'Auto-generated by Research Engine v1'
      })
      .select()
      .single();

    if (versionError) throw versionError;

    // 4. Update Topic Status to 'generated'
    await supabase
      .from('topics')
      .update({ 
        status: 'generated',
        generation_duration: duration,
        current_version: version.version_number,
        locked_at: null 
      })
      .eq('id', topicId);

    revalidatePath('/admin');
    return { success: true, versionId: version.id };

  } catch (error: any) {
    // 5. Handle Failure
    await supabase
      .from('topics')
      .update({ 
        status: 'failed',
        last_error: error.message,
        generation_attempts: (topic.generation_attempts ?? 0) + 1,
        locked_at: null 
      })
      .eq('id', topicId);

    revalidatePath('/admin');
    return { success: false, error: error.message };
  }
}
